    private void loadData() {
        String url = "jdbc:sqlite:BBC.db"; // UPDATE THIS TO YOUR ABSOLUTE PATH IF NEEDED
        
        // STRICT SQL: Ensures the bus has a valid Driver ID and Destination ID (> 0)
        String sql = "SELECT d.Name, d.time, d.KM, b.Plate_No " +
                     "FROM tbl_bus b " +
                     "INNER JOIN tbl_destinations d ON b.De_ID = d.De_ID " +
                     "WHERE b.dr_ID > 0 AND b.De_ID > 0";

        try (Connection conn = DriverManager.getConnection(url);
             PreparedStatement pstmt = conn.prepareStatement(sql);
             ResultSet rs = pstmt.executeQuery()) {

            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0); 

            while (rs.next()) {
                String destination = rs.getString("Name");
           
                String time = rs.getString("time");
                String kmStr = rs.getString("KM");
                String plateNo = rs.getString("Plate_No");

                double ticketPrice = 0.0;
                try {
                    String numericKm = kmStr.replaceAll("[^0-9.]", ""); 
                    if (!numericKm.isEmpty()) {
                        double kmValue = Double.parseDouble(numericKm);
                        ticketPrice = kmValue * 15;
                    }
                } catch (NumberFormatException e) {
                    System.out.println("Could not parse KM value: " + kmStr);
                }

                model.addRow(new Object[]{
                    destination, 
                  
                    time, 
                    kmStr, 
                    String.format("₱%.2f", ticketPrice),
                    plateNo
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading data: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    } 
