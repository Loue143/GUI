    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        int selectedRow = jTable1.getSelectedRow();

        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a destination from the table by clicking on a row!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String targetDestination = jTable1.getValueAt(selectedRow, 0).toString().trim();
        // FIX 1: Array index changed from 5 to 4 to match the 5th column!
        String targetPlate = jTable1.getValueAt(selectedRow, 4).toString().trim(); 
        
        java.util.Date date = jDateChooser1.getDate();
        
        if (date == null) {
            JOptionPane.showMessageDialog(this, "Please select a valid date from the calendar!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("MM/dd/yy");
        String selectedDate = sdf.format(date); 

        // CRITICAL: Update this to your absolute path if needed!
        String url = "jdbc:sqlite:BBC.db"; 
            
        int deId = 0, drId = 0, busId = 0, maxSeats = 0;
        String plateNo = "", kmStr = "";
        double price = 0.0;
        boolean destFound = false;

        int currentUserId = Session.Session_Class.loggedUserId;
        if (currentUserId == 0) { currentUserId = 10; }

        try (Connection conn = DriverManager.getConnection(url)) {
            
            // --- STEP 2: READ DESTINATION INFO ---
            String selectSql = "SELECT d.De_ID, d.KM, b.dr_ID, b.Plate_No, b.Bus_ID, b.seats " +
                               "FROM tbl_destinations d " +
                               "INNER JOIN tbl_bus b ON d.De_ID = b.De_ID " +
                               "WHERE d.Name = ? AND b.Plate_No = ? AND b.dr_ID > 0 AND b.De_ID > 0";
                               
            try (PreparedStatement selectStmt = conn.prepareStatement(selectSql)) {
                selectStmt.setString(1, targetDestination);
                selectStmt.setString(2, targetPlate); 
                
                try (ResultSet rs = selectStmt.executeQuery()) {
                    if (rs.next()) {
                        deId = rs.getInt("De_ID");
                        drId = rs.getInt("dr_ID");
                        plateNo = rs.getString("Plate_No");
                        kmStr = rs.getString("KM");
                        busId = rs.getInt("Bus_ID");
                        maxSeats = rs.getInt("seats");
                        destFound = true;
                    }
                } 
            }
            
            if (!destFound) {
                JOptionPane.showMessageDialog(this, "Error: No fully equipped bus found for this destination.", "Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            String numericKm = kmStr.replaceAll("[^0-9.]", ""); 
            if (!numericKm.isEmpty()) price = Double.parseDouble(numericKm) * 15;
            
            // --- STEP 3: CHECK CAPACITY ---
            String countSql = "SELECT COUNT(*) AS booked_seats FROM tbl_booking WHERE De_ID = ? AND Date = ? AND Plate = ?";
            int bookedSeats = 0;
            try (PreparedStatement countStmt = conn.prepareStatement(countSql)) {
                countStmt.setInt(1, deId);
                countStmt.setString(2, selectedDate);
                countStmt.setString(3, targetPlate); 
                try (ResultSet countRs = countStmt.executeQuery()) {
                    if (countRs.next()) bookedSeats = countRs.getInt("booked_seats");
                } 
            }
            
            if (bookedSeats >= maxSeats) {
                JOptionPane.showMessageDialog(this, "Sorry, the bus is fully booked!", "Fully Booked", JOptionPane.WARNING_MESSAGE);
                return; 
            }
            
            int displaySeatNumber = bookedSeats + 1; 

            // --- STEP 4: INSERT SEAT FIRST (FIX 2) ---
            int generatedSeatId = -1;
            String insertSeatSql = "INSERT INTO tbl_seat (Bus_ID, SeatNo) VALUES (?, ?)";
            
            // We use RETURN_GENERATED_KEYS to instantly grab the S_id SQLite creates
            try (PreparedStatement insertSeatStmt = conn.prepareStatement(insertSeatSql, java.sql.Statement.RETURN_GENERATED_KEYS)) {
                insertSeatStmt.setInt(1, busId);
                insertSeatStmt.setInt(2, displaySeatNumber);
                insertSeatStmt.executeUpdate();
                
                try (ResultSet generatedKeys = insertSeatStmt.getGeneratedKeys()) {
                    if (generatedKeys.next()) {
                        generatedSeatId = generatedKeys.getInt(1); // Grab the new S_id
                    }
                }
            }
            
            if (generatedSeatId == -1) {
                JOptionPane.showMessageDialog(this, "Error: Could not generate a seat ID.", "Database Error", JOptionPane.ERROR_MESSAGE);
                return;
            }

            // --- STEP 5: INSERT BOOKING (Now safely utilizing the generated S_id) ---
            String insertBookingSql = "INSERT INTO tbl_booking (dr_ID, De_ID, S_id, userid, Plate, Price, Date) VALUES (?, ?, ?, ?, ?, ?, ?)";
            try (PreparedStatement insertBookingStmt = conn.prepareStatement(insertBookingSql)) {
                insertBookingStmt.setInt(1, drId);
                insertBookingStmt.setInt(2, deId);
                insertBookingStmt.setInt(3, generatedSeatId); // <-- The Bridge is formed!
                insertBookingStmt.setInt(4, currentUserId); 
                insertBookingStmt.setString(5, targetPlate); 
                insertBookingStmt.setString(6, String.valueOf(price)); // Stored as TEXT per your schema
                insertBookingStmt.setString(7, selectedDate);
                insertBookingStmt.executeUpdate();
            }

            // --- STEP 6: GET USER NAME ---
            String passengerName = "Unknown Passenger";
            try {
                String userSql = "SELECT f_name, l_name FROM Tbl_user WHERE userid = ?";
                try (PreparedStatement userStmt = conn.prepareStatement(userSql)) {
                    userStmt.setInt(1, currentUserId);
                    try (ResultSet userRs = userStmt.executeQuery()) {
                        if (userRs.next()) passengerName = userRs.getString("f_name") + " " + userRs.getString("l_name");
                    }
                }
            } catch (Exception nameError) {
                System.out.println("CRASH AVOIDED: Tbl_user query failed: " + nameError.getMessage());
            }
            
            // --- STEP 7: OPEN RECEIPT PAGE ---
            String formattedPrice = String.format("₱%.2f", price);
            
            User1_3 receiptPage = new User1_3(passengerName, targetDestination, selectedDate, String.valueOf(displaySeatNumber), formattedPrice);
            receiptPage.setVisible(true);
            this.dispose();
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_jButton1ActionPerformed

