    private void loadDriverInfo() {
        int driverId = Session_Class.loggedUserId; // Assuming this holds the dr_ID
        if (driverId == 0) driverId = 1; // Fallback for testing if no one is logged in

        String url = "jdbc:sqlite:BBC.db"; 
        
        // Fetch Plate_No from tbl_bus and Destination Name from tbl_destinations
        String sql = "SELECT b.Plate_No, b.Status, d.Name AS Destination " +
                     "FROM tbl_bus b " +
                     "LEFT JOIN tbl_destinations d ON b.De_ID = d.De_ID " +
                     "WHERE b.dr_ID = ?";

        try (Connection conn = DriverManager.getConnection(url);
             PreparedStatement pstmt = conn.prepareStatement(sql)) {
             
            pstmt.setInt(1, driverId);
            
            try (ResultSet rs = pstmt.executeQuery()) {
                if (rs.next()) {
                    String dest = rs.getString("Destination");
                    String plate = rs.getString("Plate_No");
                    String currentStatus = rs.getString("Status");

                    jLabel1.setText("Your route: " + (dest != null ? dest : "Unassigned"));
                    jLabel2.setText("Plate No: " + (plate != null ? plate : "Unassigned"));
                    
                    // Optionally set the dropdown to match the current DB status
                    if (currentStatus != null && !currentStatus.isEmpty()) {
                        jComboBox1.setSelectedItem(currentStatus);
                    }
                } else {
                    jLabel1.setText("Your route: No Bus Assigned");
                    jLabel2.setText("Plate No: N/A");
                }
            }
        } catch (Exception e) {
            System.out.println("Error loading driver info: " + e.getMessage());
        }
    }

