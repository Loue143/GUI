    private void jComboBox1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox1ActionPerformed
        if (isInitializing) {
            return; 
        }

        String selectedStatus = jComboBox1.getSelectedItem().toString();
        
        // Don't update anything if they just clicked the placeholder
        if (selectedStatus.equals("Select Status...")) {
            return; 
        }

        int driverId = Session_Class.loggedUserId; 
        if (driverId == 0) driverId = 1; 

        String url = "jdbc:sqlite:BBC.db"; 
        
        // Update the status of the bus assigned to this specific driver
        String sql = "UPDATE tbl_bus SET Status = ? WHERE dr_ID = ?";

        try (Connection conn = DriverManager.getConnection(url);
             PreparedStatement pstmt = conn.prepareStatement(sql)) {
             
            pstmt.setString(1, selectedStatus);
            pstmt.setInt(2, driverId);
            
            int rowsAffected = pstmt.executeUpdate();
            
            if (rowsAffected > 0) {
                if (selectedStatus.equals("Normal / Operational")) {
                    JOptionPane.showMessageDialog(this, "Status cleared. Bus is back to normal operation.", "Success", JOptionPane.INFORMATION_MESSAGE);
                } else {
                    JOptionPane.showMessageDialog(this, "Problem Reported: " + selectedStatus + ".\nThe admin has been notified.", "Status Updated", JOptionPane.WARNING_MESSAGE);
                }
            } else {
                JOptionPane.showMessageDialog(this, "Could not update status. No bus is currently assigned to you.", "Update Failed", JOptionPane.ERROR_MESSAGE);
            }
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_jComboBox1ActionPerformed

