    public void showTableData() {
        Users.setRowSorter(null); // Reset sorter before loading data
        try {
            Class.forName("org.sqlite.JDBC");
            Connection con = DriverManager.getConnection("jdbc:sqlite:BBC.db");
            
            // Query only drivers with 'Waiting' status
            String sql = "SELECT * FROM tbl_driver WHERE Status = 'Waiting'"; 
            
            PreparedStatement pst = con.prepareStatement(sql);
            ResultSet rs = pst.executeQuery();
            
            DefaultTableModel model = (DefaultTableModel) Users.getModel();
            model.setRowCount(0); // Clears the table before loading new data
            
            while(rs.next()) {
                String id = String.valueOf(rs.getInt("dr_ID"));
                String fname = rs.getString("F_name");
                String lname = rs.getString("L_name");
                String email = rs.getString("Email");
                String username = rs.getString("User");
                String password = rs.getString("Pass");
                String status = rs.getString("Status");
                String account = rs.getString("Address"); 
                String license = rs.getString("License");
                
                String[] tbData = {id, fname, lname, email, username, password, status, account, license};
                model.addRow(tbData);
            }
            
            rs.close();
            pst.close();
            con.close();
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
            e.printStackTrace();
        }
    }
    
