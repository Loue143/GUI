    private void jToggleButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton3ActionPerformed
        int selectedRow = Users.getSelectedRow();
        
        // 1. Check if a row is selected
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a driver from the table to delete.");
            return;
        }

        // 2. Convert to model index (Crucial if the table is currently searched/filtered)
        int modelRow = Users.convertRowIndexToModel(selectedRow);
        DefaultTableModel model = (DefaultTableModel) Users.getModel();
        
        // 3. Get the ID (assuming ID is in column 0) and names for confirmation
        String id = model.getValueAt(modelRow, 0).toString();
        String fName = model.getValueAt(modelRow, 1).toString();
        String lName = model.getValueAt(modelRow, 2).toString();

        // 4. Confirm deletion
        int confirm = JOptionPane.showConfirmDialog(this, 
                "Are you sure you want to delete Driver: " + fName + " " + lName + " (ID: " + id + ")?", 
                "Confirm Deletion", 
                JOptionPane.YES_NO_OPTION,
                JOptionPane.WARNING_MESSAGE);

        if (confirm == JOptionPane.YES_OPTION) {
            try {
                Class.forName("org.sqlite.JDBC");
                Connection con = DriverManager.getConnection("jdbc:sqlite:BBC.db");
                
                // 5. Execute Delete Query
                String sql = "DELETE FROM tbl_driver WHERE dr_ID = ?";
                PreparedStatement pst = con.prepareStatement(sql);
                pst.setInt(1, Integer.parseInt(id));
                
                int rowsAffected = pst.executeUpdate();
                
                pst.close();
                con.close();
                
                if (rowsAffected > 0) {
                    JOptionPane.showMessageDialog(this, "Driver deleted successfully.");
                    showTableData(); // 6. Refresh the table!
                } else {
                    JOptionPane.showMessageDialog(this, "Error: Driver not found in database.");
                }
                
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
                e.printStackTrace();
            }
        }
    }//GEN-LAST:event_jToggleButton3ActionPerformed


