    public void showBusData() {
        try {
            Class.forName("org.sqlite.JDBC");
            Connection con = DriverManager.getConnection("jdbc:sqlite:BBC.db");
            
            // Only selects buses that do not have a Destination ID yet
            String sql = "SELECT Bus_ID, Plate_No, Bus_type, seats FROM tbl_bus WHERE Dr_ID IS NULL"; 
            PreparedStatement pst = con.prepareStatement(sql);
            ResultSet rs = pst.executeQuery();
            
            DefaultTableModel model = (DefaultTableModel) jTable2.getModel();
            model.setRowCount(0); // Clear existing data
            
            while(rs.next()) {
                String id = String.valueOf(rs.getInt("Bus_ID"));
                String plate = rs.getString("Plate_No");
                String type = rs.getString("Bus_type");
                String seats = String.valueOf(rs.getInt("seats"));
                
                model.addRow(new String[]{id, plate, type, seats});
            }
            rs.close();
            pst.close();
            con.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading buses: " + e.getMessage());
        }
    }
    
    public void showDriverData() {
        try {
            Class.forName("org.sqlite.JDBC");
            Connection con = DriverManager.getConnection("jdbc:sqlite:BBC.db");
            
            String sql = "SELECT dr_ID, F_name, L_name, Status FROM tbl_driver"; 
            PreparedStatement pst = con.prepareStatement(sql);
            ResultSet rs = pst.executeQuery();
            
            DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
            model.setRowCount(0); // Clear existing data
            
            while(rs.next()) {
                String id = String.valueOf(rs.getInt("dr_ID"));
                String name = rs.getString("F_name") + " " + rs.getString("L_name");
                String status = rs.getString("Status");
                
                model.addRow(new String[]{id, name, status});
            }
            rs.close();
            pst.close();
            con.close();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error loading drivers: " + e.getMessage());
        }}
    
