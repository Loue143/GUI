    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
       String busId = jTextField2.getText().trim();
        String driverId = jTextField5.getText().trim();
        
        if (busId.isEmpty() || driverId.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter both a Bus ID and a Driver ID.");
            return;
        }
        
        try {
            Class.forName("org.sqlite.JDBC");
            Connection con = DriverManager.getConnection("jdbc:sqlite:BBC.db");
            
            // 1. Remove this driver from their previous bus (if they had one)
            // This prevents a driver from being assigned to two buses at once
            String clearOldBusSql = "UPDATE tbl_bus SET dr_ID = NULL WHERE dr_ID = ?";
            PreparedStatement pstClear = con.prepareStatement(clearOldBusSql);
            pstClear.setInt(1, Integer.parseInt(driverId));
            pstClear.executeUpdate();
            pstClear.close();
            
            // 2. Assign the driver to the new bus
            String assignNewBusSql = "UPDATE tbl_bus SET dr_ID = ? WHERE Bus_ID = ?";
            PreparedStatement pstAssign = con.prepareStatement(assignNewBusSql);
            pstAssign.setInt(1, Integer.parseInt(driverId));
            pstAssign.setInt(2, Integer.parseInt(busId));
            
            int updated = pstAssign.executeUpdate();
            
            if (updated > 0) {
                JOptionPane.showMessageDialog(this, "Success! Driver " + driverId + " assigned to Bus " + busId);
                
                // Clear the text fields
                jTextField2.setText("");
                jTextField5.setText("");
                
                // Refresh both tables to show the latest state
                showBusData();
                showDriverData();
            } else {
                JOptionPane.showMessageDialog(this, "Update failed. Please check if the Bus ID exists.");
            }
            
            pstAssign.close();
            con.close();
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numeric IDs.");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Database Error: " + e.getMessage());
        }
    }//GEN-LAST:event_jButton1ActionPerformed


